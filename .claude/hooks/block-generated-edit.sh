#!/usr/bin/env bash
set -euo pipefail
command -v jq >/dev/null || { echo 'block-generated-edit: jq is required' >&2; exit 2; }
command -v grep >/dev/null && command -v head >/dev/null || { echo 'block-generated-edit: grep and head are required' >&2; exit 2; }
input=$(cat)
path=$(jq -er '.tool_input.file_path // .tool_input.path // empty' <<<"$input") || { echo 'block-generated-edit: file path is required' >&2; exit 2; }
root=$(git rev-parse --show-toplevel)
case $path in /*) target=$path;; *) target=$root/$path;; esac
# A file is generated only if it CARRIES the Law 1 marker as its own header:
# "@generated by <regeneration command>" within the first few lines. This is
# distinct from two classes that legitimately contain the string and MUST stay
# editable: prose/governance files that MENTION the marker (CLAUDE.md, gates.md,
# journals, state.md -- none use the "@generated by" form), and hand-authored
# GENERATOR scripts that EMIT the marker deeper in their body (scripts/gen-*.sh --
# first line is a shebang). Real generated headers are at lines 1-3; the earliest
# generator-script emission is line 6. Shebang guard + header window separate them.
if [[ -f $target ]] && [[ $(head -n 1 "$target") != '#!'* ]] \
   && head -n 5 "$target" | grep -q '@generated by'; then
  echo 'block-generated-edit: generated files are not hand-edited (Law 1)' >&2; exit 2
fi
