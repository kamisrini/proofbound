#!/usr/bin/env bash
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"; tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
mkdir "$tmp/bin"
cat >"$tmp/bin/jq" <<'EOF'
#!/usr/bin/env bash
input=$(cat)
case $* in
  *tool_input.command*) sed -nE 's/.*"command":"([^"]*)".*/\1/p' <<<"$input" ;;
  *tool_input.file_path*) sed -nE 's/.*"file_path":"([^"]*)".*/\1/p' <<<"$input" ;;
  *) exit 0 ;;
esac
EOF
chmod +x "$tmp/bin/jq"
hook_path=$tmp/bin:$PATH
printf '%s\n' '{"tool_input":{"command":"git status"}}' | PATH=$hook_path .claude/hooks/block-secrets.sh
if printf '%s\n' '{"tool_input":{"command":"git push --force origin main"}}' | PATH=$hook_path .claude/hooks/block-secrets.sh >/dev/null 2>&1; then exit 1; fi
if printf '%s\n' '{"tool_input":{"command":"printf x > docs/decisions/INDEX.md"}}' | PATH=$hook_path .claude/hooks/block-secrets.sh >/dev/null 2>&1; then exit 1; fi

# --- block-generated-edit: calibrated controls -----------------------------------
# A file is "generated" only when it CARRIES the Law 1 header marker "@generated by
# <cmd>". Controls span both true-positive classes (must BLOCK) and both
# false-positive classes the scope-blind version wrongly blocked (must SURVIVE).
bge() { printf '{"tool_input":{"file_path":"%s"}}\n' "$1" | PATH=$hook_path .claude/hooks/block-generated-edit.sh; }

# POSITIVE A (doc header, e.g. INDEX.md) -> MUST block.
printf '<!-- @generated by scripts/gen-index.sh -- regenerate with `make index` -->\n# Index\n' >"$tmp/gen-doc.md"
if bge "$tmp/gen-doc.md" >/dev/null 2>&1; then echo 'FAIL: generated doc header not blocked' >&2; exit 1; fi
# POSITIVE B (lock header with '#' comment, not a shebang, e.g. laws.lock) -> MUST block.
printf '# @generated by `make laws-lock`\n1 foo\n' >"$tmp/gen.lock"
if bge "$tmp/gen.lock" >/dev/null 2>&1; then echo 'FAIL: generated lock header not blocked' >&2; exit 1; fi

# NEUTRAL 1 (plain file) -> MUST survive.
printf 'plain\n' >"$tmp/plain.md"; bge "$tmp/plain.md"
# NEUTRAL 2 (prose class, e.g. CLAUDE.md): mentions @generated but not the marker form -> MUST survive.
printf 'Every generated artifact carries an @generated marker (Law 1).\n' >"$tmp/prose.md"; bge "$tmp/prose.md"
# NEUTRAL 3 (prose class, deep): "@generated by" appears below the header window -> MUST survive.
printf 'l1\nl2\nl3\nl4\nl5\nl6 see @generated by convention\n' >"$tmp/prose-deep.md"; bge "$tmp/prose-deep.md"
# NEUTRAL 4 (generator-script class, e.g. scripts/gen-*.sh): shebang script that EMITS the
# marker inside the header window -> MUST survive (shebang guard).
printf '#!/usr/bin/env bash\necho "@generated by make index"\n' >"$tmp/gen-script.sh"; bge "$tmp/gen-script.sh"
# FAIL-CLOSED control (Law 3): the matcher command `grep` missing -> MUST block.
# Provide every transitive dep the hook + fake jq need (bash for the fake jq's own
# shebang, cat, git, sed, head) in $tmp/bin but deliberately OMIT grep, then invoke an
# absolute bash with PATH=$tmp/bin against a GENERATED fixture. Without the dependency
# guard the hook reaches its body, the `| grep -q` pipeline fails, the condition goes
# false, and it exits 0 (ALLOW) -- a fail-OPEN on a generated file -- so this control
# genuinely dies if the guard is removed (verified by reconstructing the guard-less hook).
for c in bash cat git sed head; do ln -sf "$(command -v "$c")" "$tmp/bin/$c"; done
if printf '{"tool_input":{"file_path":"%s"}}\n' "$tmp/gen-doc.md" | PATH=$tmp/bin /bin/bash .claude/hooks/block-generated-edit.sh >/dev/null 2>&1; then echo 'FAIL: did not fail closed on missing grep' >&2; exit 1; fi
# ---------------------------------------------------------------------------------

empty=$tmp/empty; mkdir "$empty"
if printf '%s\n' '{"tool_input":{"command":"git status"}}' | PATH=$empty /bin/bash .claude/hooks/block-secrets.sh >/dev/null 2>&1; then exit 1; fi
rg -q '"PreToolUse"' .claude/settings.json
rg -q '"PostToolUse"' .claude/settings.json
rg -q '"Stop"' .claude/settings.json
