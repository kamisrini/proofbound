#!/usr/bin/env bash
set -euo pipefail

repo=${P6_TASK6_ROOT:-$(git rev-parse --show-toplevel)}
mode=${1:---check}
registry=$repo/docs/plans/p6-task6-results.tsv
artifact=$repo/docs/verification/p6-measurements-falsifiers.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

die() { echo "p6-task6-results: $*" >&2; exit 1; }
case $mode in --write|--check) ;; *) die 'usage: scripts/p6-task6-results.sh [--write|--check]' ;; esac
git -C "$repo" rev-parse --show-toplevel >/dev/null 2>&1 || die 'root is not a Git worktree'
[[ -f $registry ]] || die "missing result registry: $registry"

measurements=(artifact-authoring-minutes independent-review-field-change-rate ambiguous-obligations-preimplementation false-or-missing-commit-intent-links verdict-evidence-mismatches gate-canary-false-block-pass empty-store-reconstruction-time provider-mapping-conformance requirement-review-findings)
falsifiers=(chain-maintenance-cost artifact-role-confusion subjective-obligation-outcomes old-meaning-reconstruction applicability-boundary foreign-provider-schema-change requirement-review-rubber-stamp)
declare -A expected seen kind_of rows values provenance actions
for subject in "${measurements[@]}"; do expected[measurement:$subject]=1; kind_of[$subject]=measurement; done
for subject in "${falsifiers[@]}"; do expected[falsifier:$subject]=1; kind_of[$subject]=falsifier; done

header=0
while IFS=$'\t' read -r kind subject result value proof action extra || [[ -n ${kind:-} ]]; do
  [[ -n ${kind:-} ]] || continue
  [[ $kind == \#* ]] && continue
  if ((header == 0)); then
    [[ $kind == kind && $subject == subject && $result == result && $value == value && $proof == provenance && $action == action && -z ${extra:-} ]] || die 'invalid result registry header'
    header=1
    continue
  fi
  [[ -z ${extra:-} && -n $subject && -n $result && -n $value && -n $proof && -n $action ]] || die "incomplete row: $kind/$subject"
  [[ -n ${expected[$kind:$subject]+x} ]] || die "unknown or duplicate universe subject: $kind/$subject"
  [[ -z ${seen[$kind:$subject]+x} ]] || die "duplicate result row: $kind/$subject"
  case $kind in
    measurement) [[ $result == measured || $result == not-recoverable || $result == not-applicable ]] || die "invalid measurement result: $result" ;;
    falsifier) [[ $result == false || $result == fired || $result == indeterminate ]] || die "invalid falsifier result: $result" ;;
    *) die "invalid result kind: $kind" ;;
  esac
  [[ $action != '—' ]] || die "row has no action: $kind/$subject"
  if [[ $result == not-recoverable || $result == not-applicable || $result == indeterminate ]]; then
    [[ $value == *'not recorded'* || $value == *'no '* || $value == *'fewer '* || $value == *'one review'* || $value == *'insufficient'* ]] || die "uncertainty reason is not explicit: $kind/$subject"
  fi
  IFS=';' read -ra proofs <<<"$proof"
  ((${#proofs[@]} > 0)) || die "missing provenance: $kind/$subject"
  for item in "${proofs[@]}"; do
    case $item in
      artifact:*|session:*)
        path=${item#*:}
        git -C "$repo" ls-files --error-unmatch -- "$path" >/dev/null 2>&1 || die "unresolved provenance path: $path" ;;
      command:*) [[ -n ${item#command:} ]] || die "empty command provenance: $kind/$subject" ;;
      event:*) [[ ${item#event:} =~ ^[0-9A-Z]{20,40}$ ]] || die "invalid event provenance: $kind/$subject" ;;
      *) die "unknown provenance type: $item" ;;
    esac
  done
  seen[$kind:$subject]=1
  rows[$kind:$subject]="$value"
  values[$kind:$subject]="$result"
  provenance[$kind:$subject]="$proof"
  actions[$kind:$subject]="$action"
done <"$registry"
((header == 1)) || die 'result registry header is missing'
for subject in "${measurements[@]}"; do [[ -n ${seen[measurement:$subject]+x} ]] || die "missing measurement: $subject"; done
for subject in "${falsifiers[@]}"; do [[ -n ${seen[falsifier:$subject]+x} ]] || die "missing falsifier: $subject"; done

{
  printf '# P6 Task 6 — measurements and falsifiers\n\n'
  printf '<!-- @generated by scripts/p6-task6-results.sh --write; do not hand-edit -->\n\n'
  printf 'Authority: `docs/plans/P6-CONSOLIDATION-PLAN-draft2.md` Task 6 and `docs/plans/p6-task6-measurements-SPEC.md`.\n\n'
  printf 'Result universe: **9 measurements**, **7 falsifiers**. Every row has a closed result, typed provenance, and an action or explicit no-action statement.\n\n'
  printf '## Measurements\n\n| ID | Measurement | Result | Value | Provenance | Action |\n|---|---|---|---|---|---|\n'
  n=0
  for subject in "${measurements[@]}"; do
    n=$((n + 1))
    printf '| M-%03d | `%s` | `%s` | %s | %s | %s |\n' "$n" "$subject" "${values[measurement:$subject]}" "${rows[measurement:$subject]}" "${provenance[measurement:$subject]}" "${actions[measurement:$subject]}"
  done
  printf '\n## Falsifiers\n\n| ID | Falsifier | Result | Observation | Provenance | Action |\n|---|---|---|---|---|---|\n'
  n=0
  for subject in "${falsifiers[@]}"; do
    n=$((n + 1))
    printf '| F-%d | `%s` | `%s` | %s | %s | %s |\n' "$n" "$subject" "${values[falsifier:$subject]}" "${rows[falsifier:$subject]}" "${provenance[falsifier:$subject]}" "${actions[falsifier:$subject]}"
  done
  printf '\nAcceptance commands: `scripts/tests/p6-task6-results.test.sh`, `scripts/p6-task6-results.sh --check`, `scripts/p6-census.sh --check`, and bare `make check`.\n'
} >"$tmp"

case $mode in
  --write) install -m 0644 "$tmp" "$artifact" ;;
  --check) [[ -f $artifact ]] || die 'generated result artifact is missing'; diff -u "$artifact" "$tmp" || die 'generated result artifact is stale; run scripts/p6-task6-results.sh --write' ;;
esac
